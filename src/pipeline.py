"""
End-to-End Leak-Proof Machine Learning Pipeline.
Combines domain feature engineering, median/constant imputation,
robust scaling, one-hot encoding, and downstream classifiers into a single
scikit-learn Pipeline object ready for production serialization.
"""

from typing import List, Optional
import numpy as np
import pandas as pd
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import RobustScaler, OneHotEncoder
from sklearn.ensemble import RandomForestClassifier

try:
    from src.features import InsuranceFeatureEngineer
    from src.config import NUMERICAL_COLS, CATEGORICAL_COLS
except ImportError:
    from features import InsuranceFeatureEngineer
    from config import NUMERICAL_COLS, CATEGORICAL_COLS

# Additional numerical features generated by InsuranceFeatureEngineer
ENGINEERED_NUMERICAL_COLS = [
    "days_to_incident",
    "is_flash_claim",
    "incident_month",
    "incident_day_of_week",
    "incident_is_weekend",
    "claim_to_premium_ratio",
    "vehicle_claim_ratio",
    "injury_claim_ratio",
    "property_claim_ratio",
    "net_capital",
    "is_out_of_state_incident",
    "is_night_incident",
    "is_solo_severe_crash",
]


def build_preprocessor(
    num_cols: Optional[List[str]] = None,
    cat_cols: Optional[List[str]] = None,
) -> ColumnTransformer:
    """
    Builds the ColumnTransformer for transformed features.
    - Numerical features: Median Imputation -> RobustScaler (handles heavy claim outliers)
    - Categorical features: Constant 'MISSING' Imputation -> OneHotEncoder(handle_unknown='ignore')
    """
    if num_cols is None:
        num_cols = NUMERICAL_COLS + ENGINEERED_NUMERICAL_COLS
    if cat_cols is None:
        cat_cols = CATEGORICAL_COLS

    numerical_pipeline = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", RobustScaler()),
        ]
    )

    categorical_pipeline = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="constant", fill_value="MISSING")),
            ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
        ]
    )

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", numerical_pipeline, num_cols),
            ("cat", categorical_pipeline, cat_cols),
        ],
        remainder="drop",
    )

    return preprocessor


def build_fraud_pipeline(
    classifier=None,
    num_cols: Optional[List[str]] = None,
    cat_cols: Optional[List[str]] = None,
) -> Pipeline:
    """
    Constructs the end-to-end Pipeline:
    [Raw Claims Data]
           │
           ▼
    1. InsuranceFeatureEngineer (Temporal & Financial indicators)
           │
           ▼
    2. ColumnTransformer (Median Imputer + RobustScaler / OneHotEncoder)
           │
           ▼
    3. Classifier (e.g. Random Forest, XGBoost, Logistic Regression)
    """
    if classifier is None:
        classifier = RandomForestClassifier(
            n_estimators=200,
            max_depth=6,
            class_weight="balanced",
            random_state=42,
            n_jobs=-1,
        )

    preprocessor = build_preprocessor(num_cols=num_cols, cat_cols=cat_cols)

    fraud_pipeline = Pipeline(
        steps=[
            ("feature_engineer", InsuranceFeatureEngineer(drop_identifiers=True)),
            ("preprocessor", preprocessor),
            ("classifier", classifier),
        ]
    )

    return fraud_pipeline
